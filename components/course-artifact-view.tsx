function QuizRunner({ title, envelope }: { courseId: string; title: string; envelope: ArtifactEnvelope }) {
  const displayTitle = stripKindPrefix(title);
  const parsed = assessmentPayloadSchema.safeParse(envelope.payload);
  const payload: AssessmentPayload | null = parsed.success ? parsed.data : null;
  const groupName = useId();
  const [answers, setAnswers] = useState<Record<string, string[]>>({});
  const [checks, setChecks] = useState<Record<string, QuizAttemptResult>>({});
  const [checkingId, setCheckingId] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);
  const [submitError, setSubmitError] = useState<string | null>(null);
  const [checkError, setCheckError] = useState<string | null>(null);
  const [submitted, setSubmitted] = useState<SubmittedView | null>(null);

  if (!payload) {
    return (
      <Frame
        eyebrow="Quiz"
        icon={<ListChecks className="h-3.5 w-3.5" />}
        title={displayTitle}
        subtitle=""
        badge={<Badge className="border-[#f2d1cf] bg-[#fff4f3] text-[#a53f34]">Needs regeneration</Badge>}
      >
        <div className="mt-3 border border-[#f2d1cf] bg-[#fff4f3] p-3">
          <p className="font-body text-xs leading-5 text-[#93443d]">
            This assessment came back malformed, so nothing usable was kept. Ask the course chat to generate it again.
          </p>
        </div>
      </Frame>
    );
  }

  const isPractice = payload.mode === "practice";
  const answeredCount = payload.questions.filter((question) => (answers[question.id] ?? []).length > 0).length;
  const allAnswered = answeredCount === payload.questions.length;

  const toggleOption = (questionId: string, optionId: string, type: AssessmentQuestionType) => {
    setSubmitError(null);
    setAnswers((current) => {
      if (type === "single") return { ...current, [questionId]: [optionId] };
      const selected = current[questionId] ?? [];
      return {
        ...current,
        [questionId]: selected.includes(optionId) ? selected.filter((id) => id !== optionId) : [...selected, optionId],
      };
    });
  };

  const checkQuestion = async (questionId: string) => {
    const selected = answers[questionId] ?? [];
    if (selected.length === 0 || checkingId || submitting || submitted) return;
    setCheckingId(questionId);
    setCheckError(null);
    try {
      const response = await fetch(`/api/assessments/${envelope.id}/check`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ answers: { [questionId]: selected } }),
      });
      const data = (await response.json()) as { results?: QuizAttemptResult[]; error?: string };
      if (!response.ok || !Array.isArray(data.results) || data.results.length === 0) {
        throw new Error(data.error ?? "The answer could not be checked.");
      }
      const result = data.results[0] as QuizAttemptResult;
      setChecks((current) => ({ ...current, [questionId]: result }));
    } catch (error) {
      setCheckError(error instanceof Error ? error.message : "The answer could not be checked.");
    } finally {
      setCheckingId(null);
    }
  };

  const submit = async () => {
    if (submitting || !allAnswered || submitted) return;
    setSubmitting(true);
    setSubmitError(null);
    try {
      const response = await fetch(`/api/assessments/${envelope.id}/submit`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ answers }),
      });
      const data = (await response.json()) as { attempt?: SubmittedView; error?: string };
      if (!response.ok || !data.attempt || !Array.isArray(data.attempt.results)) {
        throw new Error(data.error ?? "The submission could not be saved.");
      }
      setSubmitted(data.attempt);
    } catch (error) {
      setSubmitError(error instanceof Error ? error.message : "The submission could not be saved.");
    } finally {
      setSubmitting(false);
    }
  };

  const retake = () => {
    setSubmitted(null);
    setChecks({});
    setAnswers({});
    setCheckError(null);
    setSubmitError(null);
  };

  return (
    <Frame
      eyebrow="Quiz"
      icon={<ListChecks className="h-3.5 w-3.5" />}
      title={displayTitle}
      subtitle={`${payload.mode === "quiz" ? "Quiz" : "Practice"} · ${payload.questions.length} question${payload.questions.length === 1 ? "" : "s"}`}
      badge={
        submitted ? (
          <Badge className="border-blue/25 bg-blue-tint text-blue">Submitted</Badge>
        ) : (
          null
        )
      }
    >
      {submitted ? (
        <SubmittedResults submitted={submitted} questions={payload.questions} onRetake={retake} />
      ) : (
        <>
          <p className="mt-1 font-body text-xs leading-5 text-text-muted">
            {isPractice
              ? "Practice mode: check each question for immediate feedback, then submit to save the attempt."
              : "Quiz mode: feedback appears after you submit. Multi-select questions need every correct option and nothing extra."}
          </p>
          <ol className="mt-2 space-y-2">
            {payload.questions.map((question, index) => {
              const selected = answers[question.id] ?? [];
              const checked = checks[question.id];
              return (
                <li key={question.id} className="border-b border-border py-2">
                  <div className="py-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <span className="font-mono text-[11px] font-medium uppercase tracking-[0.14em] text-text-dim">
                        Q{index + 1} · {question.type === "single" ? "Single choice" : "Multi-select"}
                      </span>
                      {checked && isPractice ? (
                        <Badge
                          className={checked.correct ? "border-blue/25 bg-blue-tint text-blue" : "border-[#f2d1cf] bg-[#fff4f3] text-[#a53f34]"}
                        >
                          {checked.correct ? "Correct" : "Not quite"}
                        </Badge>
                      ) : null}
                    </div>
                    <p className="mt-1 font-body text-[15px] font-medium leading-6 text-text">{question.prompt}</p>
                    <div className="mt-2 space-y-1.5" role="group" aria-label={`Question ${index + 1} options`}>
                      {question.options.map((option) => {
                        const active = selected.includes(option.id);
                        const inputId = `${groupName}-${question.id}-${option.id}`;
                        return (
                          <label
                            key={option.id}
                            htmlFor={inputId}
                            className={cn(
                              "pressable flex cursor-pointer items-start gap-2.5 border px-2.5 py-2 font-body text-sm transition-colors",
                              active ? "border-blue bg-white text-text" : "border-border bg-white text-text-muted hover:bg-bg-alt hover:text-text",
                            )}
                          >
                            <input
                              id={inputId}
                              type={question.type === "single" ? "radio" : "checkbox"}
                              name={`${groupName}-${question.id}`}
                              checked={active}
                              onChange={() => toggleOption(question.id, option.id, question.type)}
                              className="mt-1 h-3.5 w-3.5 shrink-0 accent-[#2d6a4f]"
                            />
                            <span className="leading-6">{option.text}</span>
                          </label>
                        );
                      })}
                    </div>
                    {isPractice ? (
                      <div className="mt-2.5">
                        <Button
                          type="button"
                          variant="outline"
                          size="sm"
                          disabled={selected.length === 0 || checkingId !== null}
                          onClick={() => void checkQuestion(question.id)}
                        >
                          {checkingId === question.id ? <LoaderCircle className="h-3.5 w-3.5 animate-spin" /> : <CircleHelp className="h-3.5 w-3.5" />}
                          {checked ? "Check again" : "Check answer"}
                        </Button>
                        {checked ? (
                          <div className={cn("mt-2.5 border px-3 py-2.5", checked.correct ? "border-blue/25 bg-blue-tint" : "border-border bg-paper")}>
                            <p className="flex items-center gap-1.5 font-body text-xs font-semibold text-text">
                              {checked.correct ? <CheckCircle2 className="h-3.5 w-3.5 text-blue" /> : <XCircle className="h-3.5 w-3.5 text-[#a53f34]" />}
                              {checked.correct ? "Correct." : "Not quite — the correct set is highlighted after submit."}
                            </p>
                            <p className="mt-1.5 font-body text-xs leading-5 text-text-muted">{checked.explanation}</p>
                          </div>
                        ) : null}
                      </div>
                    ) : null}
                  </div>
                </li>
              );
            })}
          </ol>
          {checkError ? <p className="mt-2 font-body text-xs text-[#a53f34]">{checkError}</p> : null}
          <div className="mt-2 flex flex-wrap items-center gap-2">
            <button
              type="button"
              disabled={!allAnswered || submitting}
              onClick={() => void submit()}
              className="pressable flex h-11 items-stretch overflow-hidden border border-blue bg-blue text-white transition-colors hover:bg-blue-hover disabled:cursor-not-allowed disabled:opacity-50"
            >
              <span className="flex flex-1 items-center justify-center px-5 font-body text-[14.5px] font-medium">
                {submitting ? <LoaderCircle className="h-4 w-4 animate-spin" /> : `Submit ${isPractice ? "practice" : "quiz"}`}
              </span>
              <span className="flex w-11 items-center justify-center border-l border-white/20">
                <ListChecks className="h-4 w-4" />
              </span>
            </button>
            <p className="font-body text-xs text-text-muted">
              {answeredCount} of {payload.questions.length} answered{!allAnswered ? " — answer all questions to submit." : ""}
            </p>
          </div>
          {submitError ? (
            <div className="mt-2.5 flex flex-wrap items-center gap-2 border border-[#f2d1cf] bg-[#fff4f3] p-3">
              <AlertCircle className="h-4 w-4 shrink-0 text-[#93443d]" />
              <p className="flex-1 font-body text-xs leading-5 text-[#93443d]">{submitError} Your answers are kept.</p>
              <Button type="button" variant="danger" size="sm" disabled={submitting} onClick={() => void submit()}>
                <RefreshCw className="h-3.5 w-3.5" /> Retry
              </Button>
            </div>
          ) : null}
        </>
      )}
      <SourceLinks artifact={envelope} />
    </Frame>
  );
}

function SubmittedResults({
  submitted,
  questions,
  onRetake,
}: {
  submitted: SubmittedView;
  questions: AssessmentPayload["questions"];
  onRetake: () => void;
}) {
  const byId = new Map(questions.map((question) => [question.id, question]));
  const correctCount = submitted.results.filter((result) => result.correct).length;
  const percent = Math.round(submitted.score * 100);
  const mastery = submitted.mastery ?? [];

  return (
    <div className="mt-2">
      <div className="border-b border-border py-2">
        <p className="font-mono text-[11px] font-medium uppercase tracking-[0.14em] text-blue">Score</p>
        <p className="mt-1 font-heading text-2xl font-medium tracking-[-0.02em] text-text">
          {percent}% · {correctCount} of {questions.length} correct
        </p>
      </div>
      {mastery.length > 0 ? (
        <div className="mt-2.5 flex flex-wrap gap-1.5">
          {mastery.map((entry) => (
            <Badge key={entry.topicKey} className="border-blue/25 bg-blue-tint text-blue">
              {entry.topicKey}: {entry.displayLabel}
            </Badge>
          ))}
        </div>
      ) : null}
      <ol className="mt-2 space-y-2">
        {submitted.results.map((result, index) => {
          const question = byId.get(result.questionId);
          if (!question) return null;
          const receivedLabels = result.received.map((id) => question.options.find((option) => option.id === id)?.text ?? "Removed option");
          const expectedLabels = result.expected.map((id) => question.options.find((option) => option.id === id)?.text ?? "Removed option");
          return (
            <li key={result.questionId} className="border-b border-border py-2">
              <p className="flex items-center gap-1.5 font-body text-xs font-semibold text-text">
                {result.correct ? <CheckCircle2 className="h-3.5 w-3.5 text-blue" /> : <XCircle className="h-3.5 w-3.5 text-[#a53f34]" />}
                Q{index + 1} · {result.correct ? "Correct" : "Incorrect"}
                <span className="ml-auto font-mono text-[11px] font-medium uppercase tracking-[0.14em] text-text-dim">{result.topicKey}</span>
              </p>
              <p className="mt-1.5 font-body text-sm font-medium leading-6 text-text">{question.prompt}</p>
              <p className="mt-1 font-body text-xs leading-5 text-text-muted">
                Your answer: {receivedLabels.length > 0 ? receivedLabels.join("; ") : "No answer"}
              </p>
              {!result.correct ? (
                <p className="mt-0.5 font-body text-xs leading-5 text-text-muted">Correct set: {expectedLabels.join("; ")}</p>
              ) : null}
              <p className="mt-1.5 font-body text-xs leading-5 text-text">{result.explanation}</p>
              {result.citations.length > 0 ? (
                <div className="mt-2 flex flex-wrap gap-1.5">
                  {result.citations.map((citation) => (
                    <Button key={citation.sourceId} type="button" variant="outline" size="xs" onClick={() => void openSourceById(citation.sourceId)}>
                      <ExternalLink className="h-3 w-3" /> {citation.title}
                    </Button>
                  ))}
                </div>
              ) : null}
            </li>
          );
        })}
      </ol>
      <div className="mt-3">
        <Button type="button" variant="outline" size="sm" onClick={onRetake}>
          <RefreshCw className="h-3.5 w-3.5" /> Retake
        </Button>
      </div>
    </div>
  );
}

const RATINGS: ReviewRating[] = ["again", "hard", "good", "easy"];

type CardReview = { cardId: string; rating: string; reviewedAt: string; nextReviewAt: string };

function DeckRunner({ title, envelope }: { title: string; envelope: ArtifactEnvelope }) {
  const displayTitle = stripKindPrefix(title);
  const parsed = flashcardDeckPayloadSchema.safeParse(envelope.payload);
  const payload = parsed.success ? parsed.data : null;
  const cards = payload?.cards ?? [];
  const [activeIndex, setActiveIndex] = useState(0);
  const [revealed, setRevealed] = useState(false);
  const [reviews, setReviews] = useState<Record<string, CardReview>>({});
  const [reviewsKey, setReviewsKey] = useState<string | null>(null);
  const [busyRating, setBusyRating] = useState<ReviewRating | null>(null);
  const [saveError, setSaveError] = useState<string | null>(null);

  const reviewsLoading = reviewsKey !== envelope.id;
  const safeIndex = cards.length === 0 ? 0 : Math.min(activeIndex, cards.length - 1);
  const activeCard = cards[safeIndex];
  const reviewedCount = cards.filter((card) => reviews[card.id]).length;

  useEffect(() => {
    if (reviewsKey === envelope.id) return;
    let cancelled = false;
    const timer = window.setTimeout(() => {
      const load = async () => {
        try {
          const response = await fetch(`/api/flashcards/${envelope.id}/reviews`, { cache: "no-store" });
          const data = (await response.json()) as { reviews?: CardReview[] };
          if (cancelled) return;
          const next: Record<string, CardReview> = {};
          if (response.ok) {
            for (const review of data.reviews ?? []) next[review.cardId] = review;
          }
          setReviews(next);
        } catch {
          if (!cancelled) setReviews({});
        } finally {
          if (!cancelled) setReviewsKey(envelope.id);
        }
      };
      void load();
    }, 0);
    return () => {
      cancelled = true;
      window.clearTimeout(timer);
    };
  }, [envelope.id, reviewsKey]);

  const go = (index: number) => {
    setActiveIndex(index);
    setRevealed(false);
    setSaveError(null);
  };

  // Global shortcuts so arrows/space work without focusing the deck first.
  // Typing targets keep native keys; focused buttons keep native space.
  useEffect(() => {
    const onKey = (event: KeyboardEvent) => {
      if (event.metaKey || event.ctrlKey || event.altKey) return;
      const target = event.target instanceof HTMLElement ? event.target : null;
      if (target?.closest("input, textarea, select, [contenteditable='true']")) return;
      if (event.key === "ArrowLeft" || event.key === "ArrowRight") {
        if (busyRating) return;
        event.preventDefault();
        go(Math.max(0, Math.min(cards.length - 1, safeIndex + (event.key === "ArrowRight" ? 1 : -1))));
      } else if (event.key === " " || event.key === "Spacebar") {
        if (target?.closest("button:not([data-flip-card]), a")) return;
        event.preventDefault();
        setRevealed((current) => !current);
      }
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  });

  const rate = async (rating: ReviewRating) => {
    if (busyRating || !activeCard) return;
    setBusyRating(rating);
    setSaveError(null);
    try {
      const response = await fetch(`/api/flashcards/${envelope.id}/review`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ cardId: activeCard.id, rating }),
      });
      const data = (await response.json()) as { review?: CardReview; error?: string };
      if (!response.ok || !data.review) throw new Error(data.error ?? "The review could not be saved.");
      const saved = data.review;
      setReviews((current) => ({ ...current, [saved.cardId]: saved }));
    } catch (error) {
      setSaveError(error instanceof Error ? error.message : "The review could not be saved.");
    } finally {
      setBusyRating(null);
    }
  };

  return (
    <Frame
      eyebrow="Flashcards"
      icon={<Layers className="h-3.5 w-3.5" />}
      title={displayTitle}
      subtitle={payload ? `${cards.length} card${cards.length === 1 ? "" : "s"}` : ""}
      badge={
        payload ? (
          null
        ) : (
          <Badge className="border-[#f2d1cf] bg-[#fff4f3] text-[#a53f34]">Needs regeneration</Badge>
        )
      }
    >
      {!payload ? (
        <div className="mt-3 border border-[#f2d1cf] bg-[#fff4f3] p-3">
          <p className="font-body text-xs leading-5 text-[#93443d]">
            This deck came back malformed, so nothing usable was kept. Ask the course chat to generate it again.
          </p>
        </div>
      ) : (
        <>
          {activeCard ? (
            <div
              className="mt-2 outline-none focus-visible:ring-2 focus-visible:ring-blue"
              tabIndex={0}
              aria-label="Flashcards. Use left and right arrows to navigate, and space to flip the card."
            >
              <div className="mb-2 flex items-center justify-between gap-3">
                <label className="flex items-center gap-2 text-xs text-text-muted">
                  Card
                  <select
                    aria-label="Jump to card"
                    className="border border-border bg-white px-2 py-1 text-xs text-text"
                    value={safeIndex}
                    disabled={busyRating !== null}
                    onChange={(event) => go(Number(event.target.value))}
                  >
                    {cards.map((card, index) => <option key={card.id} value={index}>{index + 1} of {cards.length}</option>)}
                  </select>
                </label>
                <span className="text-xs text-text-dim">{reviewedCount} of {cards.length} reviewed</span>
              </div>
              <button
                type="button"
                data-flip-card="true"
                className="flashcard-scene flex h-[min(42dvh,22rem)] min-h-52 w-full flex-col items-center border border-border bg-white px-4 py-4 text-center focus-visible:outline-2 focus-visible:outline-blue"
                aria-label={revealed ? "Show question" : "Show answer"}
                aria-pressed={revealed}
                onClick={() => setRevealed((current) => !current)}
              >
                <span className={cn("flashcard-inner", revealed && "is-flipped")}>
                  <span className="flashcard-face">
                    <span className="font-mono text-[11px] uppercase tracking-[0.14em] text-text-dim">Question</span>
                    <span className="my-auto block whitespace-pre-wrap py-4 font-body text-base leading-7 text-text">{activeCard.front}</span>
                  </span>
                  <span className="flashcard-face flashcard-back">
                    <span className="font-mono text-[11px] uppercase tracking-[0.14em] text-text-dim">Answer</span>
                    <span className="my-auto block whitespace-pre-wrap py-4 font-body text-base leading-7 text-text">{activeCard.back}</span>
                  </span>
                </span>
                <span className="pt-2 text-xs text-text-dim">Click to {revealed ? "see question" : "reveal answer"}</span>
              </button>
              <div className="mt-2 grid grid-cols-[1fr_auto_1fr] items-center gap-2">
                <Button className="justify-self-start text-xs!" type="button" variant="ghost" size="sm" disabled={safeIndex === 0 || busyRating !== null} onClick={() => go(safeIndex - 1)} aria-label="Previous card">
                  <ChevronLeft className="h-4 w-4" /> Previous
                </Button>
                <Button className="text-xs!" type="button" variant="outline" size="sm" onClick={() => setRevealed((current) => !current)}>
                  {revealed ? <EyeOff className="h-3.5 w-3.5" /> : <Eye className="h-3.5 w-3.5" />}
                  {revealed ? "Question" : "Reveal"}
                </Button>
                <Button className="justify-self-end text-xs!" type="button" variant="ghost" size="sm" disabled={safeIndex >= cards.length - 1 || busyRating !== null} onClick={() => go(safeIndex + 1)} aria-label="Next card">
                  Next <ChevronRight className="h-4 w-4" />
                </Button>
              </div>
              <p className="mt-2 text-center text-[11px] text-text-dim">← → to move · space to flip · click the card works too.</p>
              <div className="mt-3 border-t border-border pt-3">
                <p className="text-center text-xs text-text-muted">{revealed ? "How well did you remember?" : "Reveal the answer to rate your recall."}</p>
                <div className="mt-2 grid grid-cols-2 gap-2 sm:grid-cols-4" role="group" aria-label="Rate this card">
                  {RATINGS.map((rating) => (
                    <Button
                      key={rating}
                      type="button"
                      variant="outline"
                      size="sm"
                      disabled={!revealed || busyRating !== null || reviewsLoading}
                      onClick={() => void rate(rating)}
                      aria-pressed={reviews[activeCard.id]?.rating === rating}
                      className={cn("text-xs!", reviews[activeCard.id]?.rating === rating && "border-blue text-blue")}
                    >
                      {busyRating === rating ? <LoaderCircle className="h-3.5 w-3.5 animate-spin" /> : null}
                      {REVIEW_RATING_LABEL[rating]}
                    </Button>
                  ))}
                </div>
                {saveError ? <p role="alert" className="mt-2 text-xs text-[#93443d]">{saveError}</p> : null}
              </div>
            </div>
          ) : <p className="py-8 text-sm text-text-muted">This deck has no cards yet.</p>}

        </>
      )}
      <SourceLinks artifact={envelope} />
    </Frame>
  );
}
