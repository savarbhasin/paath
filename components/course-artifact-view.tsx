async function openSourceById(sourceId: string): Promise<void> {
  const response = await fetch(`/api/sources/${sourceId}/open`, { cache: "no-store" });
  const data = (await response.json()) as { url?: string; error?: string };
  if (!response.ok || !data.url) throw new Error(data.error ?? "The source could not be opened.");
  window.open(data.url, "_blank", "noopener,noreferrer");
}

type SubmittedView = {
  id: string;
  score: number;
  submittedAt: string;
  results: QuizAttemptResult[];
  mastery?: Array<{ topicKey: string; displayLabel: string; score: number; evidenceCount: number }>;
  misconceptions?: Array<{ id: string; topicKey: string; claim: string; evidenceCount: number; reinforced: boolean }>;
  memory?: { synced: number; pending: number; failed: number };
  learningWarning?: string;
};

/**
 * Stored titles already carry the kind ("Quiz · topic", "Flashcards · topic")
 * and the subtitle repeats it, so the display title drops the prefix.
 */
function stripKindPrefix(title: string): string {
  return title.replace(/^(quiz|practice|flashcards|deck)\s*·\s*/i, "").trim() || title;
}

/**
 * Renders one course-level quiz/deck (generated by the course chat, stored
 * with `notebook_id` null) outside any notebook. Quiz answering, scoring,
 * and flashcard reviews run through the same validated routes the notebook
 * block views use, so mastery and memory update identically.
 */
export function CourseArtifactView({ courseId, artifactId }: { courseId: string; artifactId: string }) {
  const [summary, setSummary] = useState<CourseArtifactSummary | null>(null);
  const [envelope, setEnvelope] = useState<(ArtifactEnvelope & { status: string; error: string | null }) | null>(null);
  const [failed, setFailed] = useState<string | null>(null);
  const [loadKey, setLoadKey] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    const timer = window.setTimeout(() => {
      const load = async () => {
        try {
          const listResponse = await fetch(`/api/course-artifacts?courseId=${courseId}`, { cache: "no-store" });
          const listPayload = (await listResponse.json()) as { artifacts?: CourseArtifactSummary[]; error?: string };
          if (!listResponse.ok || !Array.isArray(listPayload.artifacts)) {
            throw new Error(listPayload.error ?? "Course practice could not be loaded.");
          }
          const found = listPayload.artifacts.find((entry) => entry.id === artifactId) ?? null;
          if (cancelled) return;
          if (!found) throw new Error("This quiz or deck is not in this course.");
          setSummary(found);
          const artifactResponse = await fetch(`/api/artifacts?id=${artifactId}`, { cache: "no-store" });
          const artifactPayload = (await artifactResponse.json()) as {
            artifact?: ArtifactEnvelope & { status: string; error: string | null };
            error?: string;
          };
          if (cancelled) return;
          if (!artifactResponse.ok || !artifactPayload.artifact) {
            throw new Error(artifactPayload.error ?? "The artifact could not be loaded.");
          }
          setEnvelope(artifactPayload.artifact);
        } catch (error) {
          if (!cancelled) setFailed(error instanceof Error ? error.message : "The artifact could not be loaded.");
        } finally {
          if (!cancelled) setLoadKey(`${courseId}:${artifactId}`);
        }
      };
      void load();
    }, 0);
    return () => {
      cancelled = true;
      window.clearTimeout(timer);
    };
  }, [courseId, artifactId]);

  const loading = loadKey !== `${courseId}:${artifactId}`;

  return (
    <main className="min-h-screen bg-bg font-body text-text">
      <div className="mb-6 flex items-center justify-between gap-3 px-4 pt-3">
        <Link href={`/courses/${courseId}`} className="pressable font-body text-xs font-medium text-blue hover:underline">
          ← Back to course
        </Link>
        {summary && envelope && !loading && !failed ? <ManageItemButton id={artifactId} courseId={courseId} kind="artifact" title={summary.title} showLabel /> : null}
      </div>
      <section className="mx-auto w-full max-w-5xl px-4 pb-6">
        {loading ? (
          <p className="mt-6 flex items-center gap-2 font-body text-sm text-text-muted">
            <LoaderCircle className="h-4 w-4 animate-spin" /> Loading practice
          </p>
        ) : failed || !summary || !envelope ? (
          <div className="mt-6 border border-dashed border-border-strong px-6 py-12 text-center">
            <h1 className="font-heading text-xl font-medium tracking-[-0.02em] text-text">Practice not found</h1>
            <p className="mx-auto mt-2 max-w-sm font-body text-sm leading-6 text-text-muted">
              {failed ?? "It may have been removed. Generate a fresh one from the course chat."}
            </p>
          </div>
        ) : summary.kind === "assessment" ? (
          <QuizRunner key={envelope.id} courseId={courseId} title={summary.title} envelope={envelope} />
        ) : (
          <DeckRunner key={envelope.id} title={summary.title} envelope={envelope} />
        )}
      </section>
    </main>
  );
}

