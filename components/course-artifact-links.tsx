"use client";

import { useCallback, useEffect, useState } from "react";
import Link from "next/link";
import { Clapperboard, Layers, ListChecks, LoaderCircle } from "lucide-react";

import type { CourseArtifactSummary } from "@/app/api/course-artifacts/route";
import { cn } from "@/lib/utils";

/**
 * Stored titles carry the kind prefix ("Quiz · topic", "Flashcards · topic")
 * but the row already shows a kind icon, so display only the topic part.
 */
function displayTitle(title: string): string {
  return title.replace(/^(quiz|practice|flashcards|deck|video)\s*·\s*/i, "").trim() || title;
}

function videoStageLabel(artifact: CourseArtifactSummary): string {
  switch (artifact.videoStage) {
    case "queued":
      return "Queued";
    case "writing_script":
      return "Writing script";
    case "creating_visuals":
      return "Creating visuals";
    case "rendering":
      return "Rendering";
    case "ready":
      return "Ready";
    case "failed":
      return "Failed";
    default:
      if (artifact.status === "failed") return "Failed";
      if (artifact.status === "ready") return "Ready";
      return "Working";
  }
}

function isVideoPending(artifact: CourseArtifactSummary): boolean {
  if (artifact.kind !== "video") return false;
  if (artifact.status === "pending" || artifact.status === "generating") return true;
  return artifact.videoStage !== null && artifact.videoStage !== "ready" && artifact.videoStage !== "failed";
}

const POLL_INTERVAL_MS = 5000;

/**
 * Course-level quizzes, decks, and teaching videos generated by the course
 * chat (`learning_artifacts` rows with `notebook_id` null). Rendered under
 * the expanded course in the sidebar: practice rows under "Course practice",
 * video rows under a separate "Videos" group linking to the video player.
 *
 * The list polls only while a video is still pending, and reloads when the
 * course chat reports a newly queued artifact through the
 * `course-artifacts-updated` window event or the `refreshSignal` prop.
 */
export function CourseArtifactLinks({
  courseId,
  activeArtifactId,
  refreshSignal,
}: {
  courseId: string;
  activeArtifactId: string | null;
  refreshSignal?: number;
}) {
  const [artifacts, setArtifacts] = useState<CourseArtifactSummary[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [reloadKey, setReloadKey] = useState(0);

  const load = useCallback(async (signal: AbortSignal) => {
    try {
      const response = await fetch(`/api/course-artifacts?courseId=${courseId}`, {
        cache: "no-store",
        signal,
      });
      const payload = (await response.json()) as { artifacts?: CourseArtifactSummary[]; error?: string };
      if (signal.aborted) return;
      if (!response.ok || !Array.isArray(payload.artifacts)) {
        throw new Error(payload.error ?? "Course items could not be loaded.");
      }
      // Preserve-last-good-data: only replace rows on success, so a failed
      // refresh never hides saved rows or stops pending polling.
      setArtifacts(payload.artifacts);
      setError(null);
    } catch (err) {
      if (signal.aborted) return;
      setError(err instanceof Error ? err.message : "Course items could not be loaded.");
    }
  }, [courseId]);

  useEffect(() => {
    const controller = new AbortController();
    const timer = window.setTimeout(() => void load(controller.signal), 0);
    const onArtifactsUpdated = (event: Event) => {
      const detail = (event as CustomEvent<{ courseId?: unknown }>).detail;
      if (detail && typeof detail.courseId === "string" && detail.courseId !== courseId) return;
      void load(controller.signal);
    };
    window.addEventListener("course-artifacts-updated", onArtifactsUpdated);
    return () => {
      controller.abort();
      window.clearTimeout(timer);
      window.removeEventListener("course-artifacts-updated", onArtifactsUpdated);
    };
  }, [courseId, refreshSignal, reloadKey, load]);

  const hasPendingVideo = artifacts?.some(isVideoPending) ?? false;

  useEffect(() => {
    if (!hasPendingVideo) return;
    const controller = new AbortController();
    const timer = window.setInterval(() => void load(controller.signal), POLL_INTERVAL_MS);
    return () => {
      controller.abort();
      window.clearInterval(timer);
    };
  }, [hasPendingVideo, load]);

  if (!artifacts) {
    // Initial load failed: concise error with a manual retry. No automatic
    // refetch loop — the user retries explicitly.
    if (!error) return null;
    return (
      <div className="ml-4 border-l border-border py-0.5 pl-1.5" role="alert">
        <p className="px-2 py-1.5 font-body text-xs leading-5 text-[#a53f34]">{error}</p>
        <button
          type="button"
          onClick={() => setReloadKey((current) => current + 1)}
          className="pressable mx-2 mb-1 border border-border bg-paper px-2 py-1 font-body text-xs text-text-muted transition-colors hover:bg-bg-alt hover:text-text"
        >
          Retry
        </button>
      </div>
    );
  }
  const practice = artifacts.filter((artifact) => artifact.kind !== "video");
  const videos = artifacts.filter((artifact) => artifact.kind === "video");
  if (practice.length === 0 && videos.length === 0) return null;

  return (
    <>
      {practice.length > 0 ? (
        <ul className="ml-4 space-y-0.5 border-l border-border py-0.5 pl-1.5" aria-label="Course practice">
          <li aria-hidden="true" className="px-2 pb-0.5 pt-1.5 font-mono text-[10px] font-medium uppercase tracking-[0.14em] text-text-dim">
            Course practice
          </li>
          {practice.map((artifact) => {
            const active = activeArtifactId === artifact.id;
            const count = artifact.kind === "assessment" ? artifact.questionCount : artifact.cardCount;
            return (
              <li key={artifact.id} className="flex min-w-0 items-center">
                <Link
                  href={artifact.url}
                  aria-current={active ? "page" : undefined}
                  className={cn(
                    "pressable flex w-full items-center gap-1.5 border px-2 py-1.5 text-left font-body text-[13px] transition-colors",
                    active
                      ? "border-transparent bg-blue-tint text-text"
                      : "border-transparent text-text-muted hover:bg-bg-alt hover:text-text",
                  )}
                  title={artifact.title}
                >
                  {artifact.kind === "assessment" ? (
                    <ListChecks className="h-3.5 w-3.5 shrink-0" />
                  ) : (
                    <Layers className="h-3.5 w-3.5 shrink-0" />
                  )}
                  <span className="min-w-0 flex-1 truncate">{displayTitle(artifact.title)}</span>
                  {typeof count === "number" ? <span className="shrink-0 font-mono text-[10px] leading-5 text-text-dim">{count}</span> : null}
                </Link>
              </li>
            );
          })}
        </ul>
      ) : null}
      {videos.length > 0 ? (
        <ul className="ml-4 space-y-0.5 border-l border-border py-0.5 pl-1.5" aria-label="Course videos">
          <li aria-hidden="true" className="px-2 pb-0.5 pt-1.5 font-mono text-[10px] font-medium uppercase tracking-[0.14em] text-text-dim">
            Videos
          </li>
          {videos.map((artifact) => {
            const active = activeArtifactId === artifact.id;
            const pending = isVideoPending(artifact);
            const failed = artifact.status === "failed" || artifact.videoStage === "failed";
            const stage = videoStageLabel(artifact);
            return (
              <li key={artifact.id} className="flex min-w-0 items-center">
                <Link
                  href={artifact.url}
                  aria-current={active ? "page" : undefined}
                  className={cn(
                    "pressable flex w-full items-center gap-1.5 border px-2 py-1.5 text-left font-body text-[13px] transition-colors",
                    active
                      ? "border-transparent bg-blue-tint text-text"
                      : "border-transparent text-text-muted hover:bg-bg-alt hover:text-text",
                  )}
                  title={artifact.videoError ? `${artifact.title} · ${stage} · ${artifact.videoError}` : `${artifact.title} · ${stage}`}
                >
                  {pending ? (
                    <LoaderCircle className="h-3.5 w-3.5 shrink-0 animate-spin" aria-label={stage} />
                  ) : (
                    <Clapperboard className={cn("h-3.5 w-3.5 shrink-0", failed && "text-[#a53f34]")} />
                  )}
                  <span className="min-w-0 flex-1 truncate">{artifact.title}</span>
                  <span className={cn("shrink-0 font-mono text-[10px] leading-5", failed ? "text-[#a53f34]" : "text-text-dim")}>
                    {stage}
                  </span>
                </Link>
              </li>
            );
          })}
        </ul>
      ) : null}
      {error ? (
        <p className="ml-4 py-0.5 pl-3.5 font-body text-[11px] leading-5 text-text-dim" role="status">
          Refresh failed — showing saved items.{" "}
          <button
            type="button"
            onClick={() => setReloadKey((current) => current + 1)}
            className="pressable font-medium text-blue hover:underline"
          >
            Retry
          </button>
        </p>
      ) : null}
    </>
  );
}
