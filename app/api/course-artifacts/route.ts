import { NextResponse } from "next/server";
import { z } from "zod";

import { DEMO_WORKSPACE_ID } from "@/lib/config";
import { apiError } from "@/lib/server/http";
import { assessmentPayloadForArtifact, deckPayloadForArtifact } from "@/lib/server/review-study";
import { courseBelongsToWorkspace } from "@/lib/server/source-repository";
import { createSupabaseAdminClient } from "@/lib/supabase/server";
import { videoPayloadSchema, type VideoStage } from "@/lib/video";

type Row = Record<string, unknown>;

export type { VideoStage };

export type ArtifactStatus = "pending" | "generating" | "ready" | "failed";

export type CourseArtifactSummary = {
  id: string;
  kind: "assessment" | "flashcards" | "video";
  title: string;
  url: string;
  mode: "quiz" | "practice" | null;
  questionCount: number | null;
  cardCount: number | null;
  topicKeys: string[];
  createdAt: string;
  status: ArtifactStatus;
  videoStage: VideoStage | null;
  videoError: string | null;
};

function createdAtOf(entry: Row): string {
  return typeof entry.created_at === "string" ? entry.created_at : new Date(0).toISOString();
}

function statusOf(entry: Row): ArtifactStatus {
  const status = String(entry.status);
  return status === "pending" || status === "generating" || status === "ready" || status === "failed"
    ? status
    : "pending";
}

/**
 * Lists course-level study artifacts (`notebook_id` null — generated by the
 * course chat) so the sidebar can link them to the course render views.
 * Notebook-bound blocks are excluded.
 *
 * Quizzes/decks list ready rows only (unchanged behavior). Videos list all
 * states — pending, generating, failed, and ready — so in-progress and
 * failed jobs keep their sidebar rows.
 */
export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url);
    const courseId = searchParams.get("courseId") ?? "";
    if (!z.string().uuid().safeParse(courseId).success) {
      return apiError("A valid courseId is required.", 400);
    }

    const client = createSupabaseAdminClient();
    const belongs = await courseBelongsToWorkspace(client, courseId, DEMO_WORKSPACE_ID);
    if (!belongs) return apiError("The course was not found.", 404);

    const { data: practiceData, error: practiceError } = await client
      .from("learning_artifacts")
      .select("id, kind, status, payload_json, created_at")
      .eq("course_id", courseId)
      .is("notebook_id", null)
      .in("kind", ["assessment", "flashcards"])
      .eq("status", "ready")
      .order("created_at", { ascending: false })
      .limit(50);
    if (practiceError) throw new Error(`Could not list course artifacts: ${practiceError.message}`);

    const { data: videoData, error: videoError } = await client
      .from("learning_artifacts")
      .select("id, kind, status, payload_json, error, created_at")
      .eq("course_id", courseId)
      .is("notebook_id", null)
      .eq("kind", "video")
      .in("status", ["pending", "generating", "failed", "ready"])
      .order("created_at", { ascending: false })
      .limit(50);
    // Video listing failures surface as errors — a failed retrieval must
    // not masquerade as an empty Videos group.
    if (videoError) {
      throw new Error(`Could not list course videos: ${videoError.message}`);
    }

    const artifacts: CourseArtifactSummary[] = [];
    for (const entry of ((practiceData ?? []) as Row[])) {
      const id = String(entry.id);
      const kind = String(entry.kind) === "assessment" ? "assessment" : "flashcards";
      if (kind === "assessment") {
        const parsed = assessmentPayloadForArtifact(entry.payload_json);
        if (!parsed.success) continue;
        const topics = [...new Set(parsed.data.questions.map((question) => question.topicKey))].slice(0, 3);
        artifacts.push({
          id,
          kind,
          title: `${parsed.data.mode === "quiz" ? "Quiz" : "Practice"} · ${(topics[0] ?? "mixed topics").slice(0, 48)}`,
          url: `/courses/${courseId}/study/${id}`,
          mode: parsed.data.mode,
          questionCount: parsed.data.questions.length,
          cardCount: null,
          topicKeys: topics,
          createdAt: createdAtOf(entry),
          status: statusOf(entry),
          videoStage: null,
          videoError: null,
        });
      } else {
        const parsed = deckPayloadForArtifact(entry.payload_json);
        if (!parsed.success) continue;
        const topics = [...new Set(parsed.data.cards.map((card) => card.topicKey))].slice(0, 3);
        artifacts.push({
          id,
          kind,
          title: `Flashcards · ${(topics[0] ?? "mixed topics").slice(0, 48)}`,
          url: `/courses/${courseId}/study/${id}`,
          mode: null,
          questionCount: null,
          cardCount: parsed.data.cards.length,
          topicKeys: topics,
          createdAt: createdAtOf(entry),
          status: statusOf(entry),
          videoStage: null,
          videoError: null,
        });
      }
    }

    for (const entry of ((videoData ?? []) as Row[])) {
      const id = String(entry.id);
      const parsed = videoPayloadSchema.safeParse(entry.payload_json);
      if (!parsed.success) continue;
      const video = parsed.data;
      artifacts.push({
        id,
        kind: "video",
        title: video.title,
        url: `/courses/${courseId}/videos/${id}`,
        mode: null,
        questionCount: null,
        cardCount: null,
        topicKeys: video.topic ? [video.topic] : [],
        createdAt: createdAtOf(entry),
        status: statusOf(entry),
        videoStage: video.stage,
        videoError:
          typeof entry.error === "string" && entry.error ? entry.error
          : typeof video.error === "string" && video.error ? video.error
          : null,
      });
    }

    return NextResponse.json({ artifacts });
  } catch (error) {
    return apiError(error instanceof Error ? error.message : "Could not list course artifacts.");
  }
}
